#!/usr/bin/env python3
"""Generate fixed-size, block-unrolled Miden BLAKE3 benchmark programs."""

import argparse
from pathlib import Path


SIZES = (128, 256, 512, 1024, 2048)
HERE = Path(__file__).resolve().parent
TEMPLATE = HERE / "blake3.masm"
GENERATED_MARKER = "# Hash one complete chunk"


def remove_region(source: str, first: str, after: str) -> str:
    start = source.index(first)
    end = source.index(after, start)
    return source[:start] + source[end:]


def consume_block(counter: int, flags: int) -> list[str]:
    return [f"    push.{flags}.64.0.{counter}", "    exec.consume_advice_block"]


def chunk(block_count: int, counter: int, save_child: int | None = None) -> list[str]:
    lines = ["    exec.reset_cv"]
    for block in range(block_count):
        flags = (1 if block == 0 else 0) | (2 if block + 1 == block_count else 0)
        lines.extend(consume_block(counter, flags))
    if save_child is not None:
        lines.append(f"    exec.save_child_{save_child}")
    return lines


def single_chunk_main(block_count: int) -> list[str]:
    lines = ["begin", "    exec.reset_cv"]
    for block in range(block_count):
        flags = (1 if block == 0 else 0) | (10 if block + 1 == block_count else 0)
        lines.extend(consume_block(0, flags))
    lines.extend(
        [
            "    padw mem_loadw_be.20004",
            "    padw mem_loadw_be.20000",
            "    exec.sys::truncate_stack",
            "end",
        ]
    )
    return lines


def two_chunk_main() -> list[str]:
    lines = ["begin"]
    lines.extend(chunk(16, 0, 0))
    lines.extend(chunk(16, 1, 1))
    lines.extend(
        [
            "    # Parent input is child_cv[0] || child_cv[1].",
            "    exec.reset_cv",
            "    push.12.64.0.0",
            "    padw mem_loadw_be.20004",
            "    padw mem_loadw_be.20000",
            "    padw mem_loadw_be.21012",
            "    padw mem_loadw_be.21008",
            "    padw mem_loadw_be.21004",
            "    padw mem_loadw_be.21000",
            "    exec.compress_full_block",
            "    exec.sys::truncate_stack",
            "end",
        ]
    )
    return lines


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if a generated program differs from the checked-in source",
    )
    args = parser.parse_args()

    template = TEMPLATE.read_text()
    try:
        prefix = template[: template.index(GENERATED_MARKER)].rstrip()
    except ValueError as error:
        raise SystemExit(f"missing generator marker in {TEMPLATE}") from error

    # These helpers implement standalone 32/64-byte hashes and are not called
    # by the full-input compression schedule.
    prefix = remove_region(
        prefix,
        "#! Initializes four memory addresses",
        "#! Permutes ordered message words",
    )
    prefix = remove_region(
        prefix,
        "#! Blake3 2-to-1 hash function",
        "# Compress one full 64-byte BLAKE3 block.",
    ).rstrip()

    for size in SIZES:
        program_name = f"blake3_{size}"
        output_dir = HERE.parent / program_name
        output_dir.mkdir(exist_ok=True)
        body = two_chunk_main() if size == 2048 else single_chunk_main(size // 64)
        size_prefix = prefix
        if size < 2048:
            size_prefix = prefix[: prefix.index("proc save_child_0")].rstrip()
        source = "\n".join(
            [
                size_prefix,
                "",
                f"# Generated by blake3/generate_programs.py for {size} input bytes.",
                "# The input-size branch and block loop are fully unrolled.",
                *body,
                "",
            ]
        )
        output = output_dir / f"{program_name}.masm"
        if args.check:
            if not output.exists() or output.read_text() != source:
                raise SystemExit(f"generated program is stale: {output}")
        else:
            output.write_text(source)


if __name__ == "__main__":
    main()
